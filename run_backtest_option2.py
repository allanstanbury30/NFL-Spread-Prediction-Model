#!/usr/bin/env python3
"""
run_backtest.py
===============

Master orchestration script for the NFL Point Spreads Analyzer.

Pipeline
--------
Component #1:
    nfl_opponent_adjusted_engine.py
    -> leakage-safe opponent-adjusted EPA/play and Success Rate snapshots

Component #2:
    prior_season_continuity_blender.py
    -> prior-season / current-season blending with HC / OC / QB continuity

Component #3:
    nfl_spread_prediction_engine.py
    -> regression model, predicted home margin, market edge, ATS simulation

Backtest design
---------------
Default architecture:
    Training seasons: 2018-2023
    Test seasons:     2024-2025

For a target season/week, the model is fit only on games from:
    - earlier seasons, plus
    - earlier weeks of the same season

All games in the target week are predicted together before any result from that
week is allowed into the training set.

The current-season team ratings for Week N are generated by Component #1 using
only Weeks < N. Week 1 has no current-season sample and therefore relies on the
prior-season / fallback logic in Component #2.

Market convention
-----------------
Component #3 expects:
    close_spread_home < 0  -> home favorite
    close_spread_home > 0  -> home underdog

Example:
    Home -3.5 => close_spread_home = -3.5

If no external --market file is provided, this script can use nflverse schedule
market fields. nflverse's schedule `spread_line` is converted to the above
convention by NEGATING it.

External market file
--------------------
Preferred schema:
    game_id
    close_spread_home
    close_total                         optional
    close_home_ml                       optional
    close_away_ml                       optional
    bet_american_odds_home              optional
    bet_american_odds_away              optional
    closing_line_timestamp_utc          optional

If game_id is unavailable, the file may instead provide:
    season
    week
    home_team
    away_team

The external file should already normalize the HOME spread so favorites are
negative.

Continuity file
---------------
Required columns:
    season
    team
    hc_retained
    oc_retained
    qb_retained

Values may be True/False, 1/0, yes/no, retained/changed, same/new.

Example usage
-------------
python run_backtest.py \
    --continuity data/context/team_continuity.csv \
    --market data/market/nfl_market_history.csv \
    --train-start 2018 \
    --train-end 2023 \
    --test-start 2024 \
    --test-end 2025 \
    --model ridge \
    --thresholds 1.0 1.5 2.0 2.5 3.0 \
    --output-dir data/backtest

Dependencies
------------
pip install nflreadpy pandas numpy scikit-learn pyarrow

Optional:
pip install xgboost
"""

