def choose_model_features(c3, dataset: pd.DataFrame) -> List[str]:
    """
    Build the final kickoff-time feature list.

    Component #3 supplies the core market + team-strength features.
    This orchestrator appends the four scheduling/context features:

        net_rest
        travel_distance_diff
        is_divisional
        tz_shifted

    The older aliases rest_diff and division_game are removed whenever the
    richer canonical replacements are present, avoiding duplicated inputs.
    """
    features = list(c3.default_model_features(dataset))

    if "net_rest" in dataset.columns:
        features = [f for f in features if f != "rest_diff"]

    if "is_divisional" in dataset.columns:
        features = [f for f in features if f != "division_game"]

    for extra in (
        "market_home_win_prob",
        "market_away_win_prob",
        "net_rest",
        "travel_distance_diff",
        "is_divisional",
        "tz_shifted",
    ):
        if extra in dataset.columns and extra not in features:
            features.append(extra)

    return features


def weekly_walk_forward_predict(
    c3,
    dataset: pd.DataFrame,
    *,
    feature_columns: Sequence[str],
    test_start: int,
    test_end: int,
    config: BacktestConfig,
) -> pd.DataFrame:
    """
    Weekly walk-forward simulation.

    Before target Season S, Week W:
      training rows =
          season < S
          OR
          (season == S AND week < W)

    Every game in the target week is predicted from the same fitted model, so
    no result from that week can influence another prediction in that week.
    """
    print("\n[4/5] COMPONENT #3 - Weekly walk-forward model")

    df = dataset.copy().sort_values(
        ["season", "week", "kickoff_utc", "game_id"]
    ).reset_index(drop=True)

    model_cfg = c3.ModelConfig(
        model_type=config.model_type,
        ridge_alpha=config.model_ridge_alpha,
        min_train_games=config.min_train_games,
        max_train_seasons=config.max_train_seasons,
        default_american_odds=config.default_american_odds,
    )

    prediction_blocks: List[pd.DataFrame] = []

    for season in range(test_start, test_end + 1):
        season_test = df[df["season"] == season]
        if season_test.empty:
            print(f"  WARNING: no model rows for test season {season}")
            continue

        weeks = sorted(int(w) for w in season_test["week"].dropna().unique())

        for week in weeks:
            test = df[
                (df["season"] == season)
                & (df["week"] == week)
            ].copy()

            train = df[
                (df["season"] < season)
                | (
                    (df["season"] == season)
                    & (df["week"] < week)
                )
            ].copy()

            if config.max_train_seasons is not None and not train.empty:
                min_season = season - config.max_train_seasons
                train = train[train["season"] >= min_season].copy()

            train = train.dropna(subset=["home_margin"])

            if len(train) < config.min_train_games:
                print(
                    f"  SKIP {season} W{week}: "
                    f"{len(train)} training games < "
                    f"{config.min_train_games}"
                )
                continue

            # Explicit time-cut validation.
            same_or_future_week = (
                (train["season"] > season)
                | (
                    (train["season"] == season)
                    & (train["week"] >= week)
                )
            )
            if same_or_future_week.any():
                raise AssertionError(
                    f"Leakage in model training for {season} Week {week}."
                )

            model = c3.make_model(feature_columns, model_cfg)

            model.fit(
                train[list(feature_columns)],
                train["home_margin"].astype(float),
            )

            pred = model.predict(test[list(feature_columns)])

            keep = [
                c for c in (
                    "game_id",
                    "season",
                    "week",
                    "kickoff_utc",
                    "home_team",
                    "away_team",
                    "home_score",
                    "away_score",
                    "home_margin",
                    "close_spread_home",
                    "bet_spread_home",
                    "close_total",
                    "bet_american_odds_home",
                    "bet_american_odds_away",
                )
                if c in test.columns
            ]

            block = test[keep].copy()
            block["predicted_home_margin"] = pred
            block["model_edge_home_close"] = (
                block["predicted_home_margin"]
                + block["close_spread_home"]
            )
            block["model_edge_home_bet"] = (
                block["predicted_home_margin"]
                + block["bet_spread_home"]
            )
            block["train_games"] = len(train)
            block["model_type"] = config.model_type

            prediction_blocks.append(block)

        predicted_games = sum(
            len(b)
            for b in prediction_blocks
            if not b.empty and int(b["season"].iloc[0]) == season
        )
        print(
            f"  {season}: {predicted_games:,} out-of-sample predictions"
        )

    if not prediction_blocks:
        return pd.DataFrame()

    return pd.concat(prediction_blocks, ignore_index=True)


