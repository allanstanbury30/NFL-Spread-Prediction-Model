# ---------------------------------------------------------------------------
# MANUAL OVERRIDES
# ---------------------------------------------------------------------------
#
# Add project-specific overrides here. Values omitted from an override keep
# their generated value.
#
# Example:
#
# MANUAL_OVERRIDES = {
#     (2024, "LV"): {"hc_retained": 0},
#     (2024, "BUF"): {"oc_retained": 1},
# }
# ---------------------------------------------------------------------------

MANUAL_OVERRIDES: Dict[Tuple[int, str], Dict[str, int]] = {}


def canonical_team(team: str) -> str:
    """Normalize historical/team-code aliases to the project's canonical code."""
    code = str(team).strip().upper()
    return TEAM_ALIASES.get(code, code)


def _validate_binary(value: int, label: str) -> int:
    value = int(value)
    if value not in (0, 1):
        raise ValueError(f"{label} must be 0 or 1; got {value!r}")
    return value


def build_continuity_table(
    start_season: int = START_SEASON,
    end_season: int = END_SEASON,
    overrides: Optional[
        Mapping[Tuple[int, str], Mapping[str, int]]
    ] = None,
) -> Dict[int, Dict[str, Dict[str, int]]]:
    """
    Build the complete nested dictionary:

    {
        2024: {
            "KC": {
                "hc_retained": 1,
                "oc_retained": 1,
                "qb_retained": 1,
            },
            ...
        },
        ...
    }

    `overrides` are applied after the curated defaults.
    """
    if start_season < START_SEASON or end_season > END_SEASON:
        raise ValueError(
            f"Curated coverage is {START_SEASON}-{END_SEASON}; "
            f"requested {start_season}-{end_season}."
        )
    if start_season > end_season:
        raise ValueError("start_season must be <= end_season")

    merged_overrides: Dict[Tuple[int, str], Dict[str, int]] = {
        (int(season), canonical_team(team)): dict(values)
        for (season, team), values in MANUAL_OVERRIDES.items()
    }

    if overrides:
        for (season, team), values in overrides.items():
            key = (int(season), canonical_team(team))
            merged_overrides.setdefault(key, {}).update(dict(values))

    table: Dict[int, Dict[str, Dict[str, int]]] = {}

    for season in range(start_season, end_season + 1):
        table[season] = {}

        for team in NFL_TEAMS:
            flags = {
                "hc_retained": int(team not in HC_CHANGED[season]),
                "oc_retained": int(team not in OC_CHANGED[season]),
                "qb_retained": int(team not in QB_CHANGED[season]),
            }

            override = merged_overrides.get((season, team), {})
            for field, value in override.items():
                if field not in flags:
                    raise KeyError(
                        f"Unknown override field {field!r} for {season} {team}"
                    )
                flags[field] = _validate_binary(
                    value,
                    f"{season} {team} {field}",
                )

            table[season][team] = flags

    validate_continuity_table(
        table,
        start_season=start_season,
        end_season=end_season,
    )
    return table


def get_continuity(
    team: str,
    season: int,
    overrides: Optional[
        Mapping[Tuple[int, str], Mapping[str, int]]
    ] = None,
) -> Dict[str, int]:
    """
    Return one team's continuity flags for one target season.

    Example:
        get_continuity("KC", 2024)
    """
    season = int(season)
    team = canonical_team(team)

    if team not in NFL_TEAMS:
        raise KeyError(f"Unknown team code: {team}")

    table = build_continuity_table(
        start_season=season,
        end_season=season,
        overrides=overrides,
    )
    return dict(table[season][team])


def continuity_for_season(
    season: int,
    overrides: Optional[
        Mapping[Tuple[int, str], Mapping[str, int]]
    ] = None,
) -> Dict[str, Dict[str, int]]:
    """
    Return Component #2-friendly dictionary for one season:

    {
        "KC": {"hc_retained": 1, "oc_retained": 1, "qb_retained": 1},
        ...
    }
    """
    season = int(season)
    return build_continuity_table(
        start_season=season,
        end_season=season,
        overrides=overrides,
    )[season]


def continuity_to_dataframe(
    start_season: int = START_SEASON,
    end_season: int = END_SEASON,
    overrides: Optional[
        Mapping[Tuple[int, str], Mapping[str, int]]
    ] = None,
    include_notes: bool = False,
) -> pd.DataFrame:
    """
    Convert the full mapping into the exact DataFrame schema expected by
    run_backtest.py.
    """
    table = build_continuity_table(
        start_season=start_season,
        end_season=end_season,
        overrides=overrides,
    )

    rows = []
    for season, teams in table.items():
        for team, flags in teams.items():
            row = {
                "season": season,
                "team": team,
                **flags,
            }
            if include_notes:
                row["note"] = AMBIGUITY_NOTES.get((season, team), "")
            rows.append(row)

    df = pd.DataFrame(rows).sort_values(
        ["season", "team"]
    ).reset_index(drop=True)

    return df


def write_continuity_csv(
    path: str | Path = "data/context/team_continuity.csv",
    *,
    start_season: int = START_SEASON,
    end_season: int = END_SEASON,
    overrides: Optional[
        Mapping[Tuple[int, str], Mapping[str, int]]
    ] = None,
    include_notes: bool = False,
) -> Path:
    """
    Write the exact CSV consumed by run_backtest.py.

    Returns the resolved Path so it can be passed directly into run_backtest().
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    df = continuity_to_dataframe(
        start_season=start_season,
        end_season=end_season,
        overrides=overrides,
        include_notes=include_notes,
    )

    df.to_csv(path, index=False)
    return path.resolve()


def ensure_backtest_continuity_csv(
    path: str | Path = "data/context/team_continuity.csv",
) -> str:
    """
    One-line adapter for the master orchestrator.

    Example:
        continuity_path = ensure_backtest_continuity_csv()
        run_backtest(continuity_path=continuity_path, ...)
    """
    return str(write_continuity_csv(path))


def validate_continuity_table(
    table: Mapping[int, Mapping[str, Mapping[str, int]]],
    *,
    start_season: int = START_SEASON,
    end_season: int = END_SEASON,
) -> None:
    """Fail loudly if the map is incomplete or contains non-binary flags."""
    expected_seasons = set(range(start_season, end_season + 1))
    actual_seasons = set(table.keys())

    if actual_seasons != expected_seasons:
        raise AssertionError(
            f"Season coverage mismatch. "
            f"Expected {sorted(expected_seasons)}, got {sorted(actual_seasons)}"
        )

    expected_teams = set(NFL_TEAMS)

    for season in sorted(expected_seasons):
        teams = table[season]
        actual_teams = set(teams.keys())

        if actual_teams != expected_teams:
            missing = sorted(expected_teams - actual_teams)
            extra = sorted(actual_teams - expected_teams)
            raise AssertionError(
                f"{season}: team coverage mismatch. "
                f"Missing={missing}, extra={extra}"
            )

        for team, flags in teams.items():
            required = {"hc_retained", "oc_retained", "qb_retained"}
            if set(flags.keys()) != required:
                raise AssertionError(
                    f"{season} {team}: expected fields {required}, "
                    f"got {set(flags.keys())}"
                )

            for field, value in flags.items():
                if int(value) not in (0, 1):
                    raise AssertionError(
                        f"{season} {team} {field} is not binary: {value}"
                    )


def summarize_changes(
    start_season: int = START_SEASON,
    end_season: int = END_SEASON,
) -> pd.DataFrame:
    """Quick QC table showing how many teams receive 0 for each role."""
    df = continuity_to_dataframe(
        start_season=start_season,
        end_season=end_season,
    )

    summary = (
        df.assign(
            hc_changed=1 - df["hc_retained"],
            oc_changed=1 - df["oc_retained"],
            qb_changed=1 - df["qb_retained"],
        )
        .groupby("season", as_index=False)[
            ["hc_changed", "oc_changed", "qb_changed"]
        ]
        .sum()
    )

    return summary


